@given(
    missing_vars=missing_vars_strategy,
    present_values=st.lists(safe_value_strategy, min_size=0, max_size=10),
)
@settings(max_examples=100)
def test_missing_required_vars_always_produce_failures(
    missing_vars: list[str],
    present_values: list[str],
):
    """
    # Feature: deploy-readiness-audit, Property 13: All required env vars documented in .env.example

    For any subset of required environment variables that are absent from
    infra/.env.example, the checker SHALL produce exactly one failure per
    missing variable.

    Validates: Requirements 8.4
    """
    present_vars = [v for v in REQUIRED_ENV_VARS if v not in missing_vars]

    with tempfile.TemporaryDirectory() as tmpdir:
        tmp_path = Path(tmpdir)
        env_example = tmp_path / ".env.example"

        lines = [f"{var}=somevalue\n" for var in present_vars]
        env_example.write_text("".join(lines))

        details, failures = check_env_example_completeness(env_example)

        # Every missing var must appear in failures
        for var in missing_vars:
            assert any(var in f for f in failures), (
                f"Expected failure for missing var {var!r}, but not found in: {failures}"
            )

        # The number of failures must equal the number of missing vars
        assert len(failures) == len(missing_vars), (
            f"Expected {len(missing_vars)} failures for missing vars {missing_vars}, "
            f"but got {len(failures)}: {failures}"
        )


@given(
    extra_vars=st.lists(
        st.text(
            alphabet="ABCDEFGHIJKLMNOPQRSTUVWXYZ_",
            min_size=1,
            max_size=20,
        ).filter(lambda s: s not in REQUIRED_ENV_VARS and s[0].isalpha()),
        min_size=0,
        max_size=5,
        unique=True,
    ),
    values=st.lists(safe_value_strategy, min_size=7, max_size=7),
)
@settings(max_examples=100)
def test_all_required_vars_present_with_extras_passes(
    extra_vars: list[str],
    values: list[str],
):
    """
    # Feature: deploy-readiness-audit, Property 13: All required env vars documented in .env.example

    For any .env.example that contains all required variables (plus any number
    of extra variables), the checker SHALL produce no failures.

    Validates: Requirements 8.4
    """
    with tempfile.TemporaryDirectory() as tmpdir:
        tmp_path = Path(tmpdir)
        env_example = tmp_path / ".env.example"

        lines = [f"{var}={val}\n" for var, val in zip(REQUIRED_ENV_VARS, values)]
        for extra in extra_vars:
            lines.append(f"{extra}=extravalue\n")

        env_example.write_text("".join(lines))

        details, failures = check_env_example_completeness(env_example)
        assert failures == [], (
            f"Expected no failures when all required vars are present, "
            f"but got: {failures}"
        )


@given(
    var=st.sampled_from(REQUIRED_ENV_VARS),
    value=safe_value_strategy,
    comment_prefix=st.text(
        alphabet="abcdefghijklmnopqrstuvwxyz ",
        min_size=0,
        max_size=20,
    ),
)
@settings(max_examples=100)
def test_commented_out_var_not_counted_as_documented(
    var: str,
    value: str,
    comment_prefix: str,
):
    """
    # Feature: deploy-readiness-audit, Property 13: All required env vars documented in .env.example

    A required variable that only appears in a comment line (starting with #)
    SHALL NOT be counted as documented — only uncommented key=value lines count.

    Validates: Requirements 8.4
    """
    # Build a file where the var only appears in a comment
    other_vars = [v for v in REQUIRED_ENV_VARS if v != var]

    with tempfile.TemporaryDirectory() as tmpdir:
        tmp_path = Path(tmpdir)
        env_example = tmp_path / ".env.example"

        lines = [f"# {comment_prefix}{var}={value}\n"]  # commented out
        lines += [f"{v}=somevalue\n" for v in other_vars]
        env_example.write_text("".join(lines))

        details, failures = check_env_example_completeness(env_example)

        assert any(var in f for f in failures), (
            f"Expected failure for {var!r} that only appears in a comment, "
            f"but not found in failures: {failures}"
        )


@given(
    var=st.sampled_from(REQUIRED_ENV_VARS),
    value=safe_value_strategy,
)
@settings(max_examples=100)
def test_each_required_var_individually_detected_when_missing(
    var: str,
    value: str,
):
    """
    # Feature: deploy-readiness-audit, Property 13: All required env vars documented in .env.example

    For each individual required variable, when it is the only one missing from
    .env.example, the checker SHALL produce exactly one failure naming that variable.

    Validates: Requirements 8.4
    """
    other_vars = [v for v in REQUIRED_ENV_VARS if v != var]

    with tempfile.TemporaryDirectory() as tmpdir:
        tmp_path = Path(tmpdir)
        env_example = tmp_path / ".env.example"

        lines = [f"{v}=somevalue\n" for v in other_vars]
        env_example.write_text("".join(lines))

        details, failures = check_env_example_completeness(env_example)

        assert len(failures) == 1, (
            f"Expected exactly 1 failure when only {var!r} is missing, "
            f"but got {len(failures)}: {failures}"
        )
        assert var in failures[0], (
            f"Expected failure to mention {var!r}, but got: {failures[0]!r}"
        )
